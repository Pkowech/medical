import React from 'react';
import Link from 'next/link';
import {
  BookOpen,
  Brain,
  CalendarDays,
  ChevronRight,
  Flame,
  GraduationCap,
  Route,
  Target,
  Upload,
  Users,
} from 'lucide-react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { useRouter } from 'next/navigation';
import ProgressBar from '@/shared/components/ui/ProgressBar';
import { useStudy } from '@/features/learning-management/study/hooks/useStudy';
import { AutoGeneratedQuizCard } from '@/features/assessment/components/auto-generated-quiz-card';
import type { StudyStats } from '@/shared/types/progressInterface';
import { GoalsProgressWidget } from '@/features/learning-management/components/goals/goals-progress-widget';
import { ReviewQueue } from './ReviewQueue';
import { useAuthStore } from '@/features/auth/store/useAuthStore';
import { useProgress } from '@/shared/hooks/useProgress';
import apiService from '@/features/auth/services/apiClient';

// Minimal local types to avoid using `any` and keep this component focused
type CourseProgress = { id: string; name: string; progressPercentage: number; lastUpdated?: number };
type UnitProgress = { id: string; name: string; courseId: string; progressPercentage: number; lastUpdated?: number };
type PeerStats = {
  userPercentile: number;
  averageScore: number;
  userScore: number;
  cohortLabel?: string;
};
type AutoGeneratedQuiz = {
  id: string;
  quizId: string;
  quizTitle: string;
  weaknessTopicId: string;
  weaknessTopicName: string;
  riskLevel: 'HIGH' | 'MEDIUM' | 'LOW';
  detectedAt: string;
  oldMastery?: number;
};

interface StudyPlannerData {
  stats: StudyStats;
  courseProgress: CourseProgress[];
  unitProgress: UnitProgress[];
}

export const StudyDashboard: React.FC = () => {
  const { getStudyStats, getCourseProgress, getUnitProgress } = useStudy();
  const router = useRouter();
  const queryClient = useQueryClient();
  const userId = useAuthStore(state => state.user?.id);
  const { progressData } = useProgress();
  const {
    data: dashboard,
    isLoading,
    isError,
    error,
    refetch,
  } = useQuery<StudyPlannerData>({
    queryKey: ['studyPlanner', userId],
    queryFn: async () => {
      if (!userId) throw new Error('User is not authenticated.');
      const [stats, courseProgress, unitProgress] = await Promise.all([
        getStudyStats(),
        getCourseProgress(),
        getUnitProgress(),
      ]);
      return { stats, courseProgress, unitProgress };
    },
    enabled: Boolean(userId),
    staleTime: 2 * 60 * 1000,
    gcTime: 10 * 60 * 1000,
    meta: { persist: Boolean(userId) },
  });
  const {
    data: autoQuizzes = [],
    isError: autoQuizzesError,
  } = useQuery<AutoGeneratedQuiz[]>({
    queryKey: ['autoGeneratedQuizzes', userId],
    queryFn: async () => {
      const response = await apiService.get<{ data: AutoGeneratedQuiz[] }>(
        '/quizzes/assessments/auto-generated-quizzes',
      );
      return response.data.data;
    },
    enabled: Boolean(userId),
    staleTime: 5 * 60 * 1000,
    gcTime: 10 * 60 * 1000,
    meta: { persist: Boolean(userId) },
  });
  const stats = dashboard?.stats;
  const courseProgress = dashboard?.courseProgress ?? [];
  const unitProgress = dashboard?.unitProgress ?? [];
  const peerComparison = progressData?.peerComparison;
  const peerStats: PeerStats | null = peerComparison
    ? {
        userPercentile:
          peerComparison.percentile !== undefined
            ? peerComparison.percentile
            : peerComparison.totalStudents > 0
            ? Math.max(
                0,
                Math.round(
                  (1 - peerComparison.rank / peerComparison.totalStudents) * 100,
                ),
              )
            : 0,
        averageScore: peerComparison.cohortAverage,
        userScore: peerComparison.yourAverage,
        cohortLabel: peerComparison.cohortLabel,
      }
    : null;

  if (isLoading) {
    return (
      <div className="min-h-[60vh] space-y-4" aria-label="Loading study planner">
        <div className="grid gap-4 md:grid-cols-2">
          <div className="h-32 animate-pulse rounded-xl bg-secondary dark:bg-card" />
          <div className="h-32 animate-pulse rounded-xl bg-secondary dark:bg-card" />
        </div>
        <div className="h-48 animate-pulse rounded-xl bg-secondary dark:bg-card" />
        <div className="h-48 animate-pulse rounded-xl bg-secondary dark:bg-card" />
      </div>
    );
  }

  if (isError) {
    return (
      <div role="alert" className="rounded-2xl border border-red-200 bg-card p-8 text-center dark:border-red-900 dark:bg-card">
        <h2 className="text-lg font-semibold text-foreground dark:text-foreground">Study data is unavailable</h2>
        <p className="mt-2 text-sm text-muted-foreground dark:text-muted-foreground">
          {error instanceof Error ? error.message : 'We could not load your study progress.'}
        </p>
        <button
          type="button"
          onClick={() => void refetch()}
          className="mt-4 rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white hover:bg-indigo-700"
        >
          Try again
        </button>
      </div>
    );
  }

  // Format lastUpdated timestamp for display
  const formatLastUpdated = (timestamp?: number): string => {
    if (!timestamp) return 'Not synced';
    const now = Date.now();
    const diffMs = now - timestamp;
    const diffMins = Math.floor(diffMs / 60000);
    if (diffMins < 1) return 'Just now';
    if (diffMins < 60) return `${diffMins}m ago`;
    const diffHours = Math.floor(diffMins / 60);
    if (diffHours < 24) return `${diffHours}h ago`;
    const diffDays = Math.floor(diffHours / 24);
    return `${diffDays}d ago`;
  };

  return (
    <div className="min-w-0 space-y-4 bg-background/50 dark:bg-card/50">
      <section aria-labelledby="study-planner-actions" className="space-y-3">
        <div>
          <h2 id="study-planner-actions" className="text-lg font-semibold text-foreground">
            Plan your studies
          </h2>
          <p className="text-sm text-muted-foreground">
            Schedule focused sessions, keep goals on track, and organize your resources.
          </p>
        </div>
        <nav aria-label="Study planner tools" className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
          {[
            {
              href: '/study-planner/schedule',
              label: 'Schedule',
              description: 'Plan study sessions, classes, and exams.',
              action: 'View schedule',
              icon: CalendarDays,
            },
            {
              href: '/study-planner/goals',
              label: 'Goals',
              description: 'Set learning targets and track progress.',
              action: 'Manage goals',
              icon: Target,
            },
            {
              href: '/study-planner/materials',
              label: 'Study materials',
              description: 'Browse your saved study resources.',
              action: 'Browse materials',
              icon: BookOpen,
            },
            {
              href: '/study-planner/materials/upload',
              label: 'Upload materials',
              description: 'Add notes and files to your library.',
              action: 'Upload a file',
              icon: Upload,
            },
          ].map(({ href, label, description, action, icon: Icon }) => (
            <Link
              key={href}
              href={href}
              className="group flex min-h-36 flex-col rounded-xl border border-border bg-card/80 p-4 shadow-sm transition-colors hover:border-blue-300 hover:bg-background focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 dark:border-border dark:bg-card/70 dark:hover:border-blue-800 dark:hover:bg-card"
            >
              <span className="mb-3 inline-flex h-10 w-10 items-center justify-center rounded-lg bg-blue-50 text-blue-600 dark:bg-blue-950/50 dark:text-blue-300">
                <Icon aria-hidden="true" className="h-5 w-5" />
              </span>
              <span className="font-semibold text-foreground">{label}</span>
              <span className="mt-1 flex-1 text-sm text-muted-foreground">{description}</span>
              <span className="mt-3 inline-flex items-center gap-1 text-sm font-medium text-blue-700 dark:text-blue-300">
                {action}
                <ChevronRight aria-hidden="true" className="h-4 w-4 transition-transform group-hover:translate-x-0.5" />
              </span>
            </Link>
          ))}
        </nav>
      </section>

      <section aria-labelledby="study-connections" className="space-y-3">
        <div>
          <h2 id="study-connections" className="text-lg font-semibold text-foreground">
            Learn, practice, and connect
          </h2>
          <p className="text-sm text-muted-foreground">
            Pick a course or learning path, practice a topic, or study with a group.
          </p>
        </div>
        <nav
          aria-label="Courses, practice, and study groups"
          className="grid grid-cols-2 gap-2 sm:grid-cols-3 xl:grid-cols-6"
        >
          {[
            { href: '/courses', label: 'Courses', icon: GraduationCap },
            { href: '/learning-paths', label: 'Learning paths', icon: Route },
            { href: '/assessment', label: 'Quizzes', icon: Brain },
            { href: '/flashcards', label: 'Flashcards', icon: BookOpen },
            { href: '/clinical-cases', label: 'Clinical cases', icon: Target },
            { href: '/study-groups', label: 'Study groups', icon: Users },
          ].map(({ href, label, icon: Icon }) => (
            <Link
              key={href}
              href={href}
              className="flex min-h-14 items-center gap-2 rounded-lg border border-border bg-card/80 px-3 py-2 text-sm font-medium text-foreground transition-colors hover:bg-background focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 dark:bg-card/70 dark:hover:bg-card"
            >
              <Icon aria-hidden="true" className="h-4 w-4 shrink-0 text-blue-600 dark:text-blue-400" />
              <span>{label}</span>
            </Link>
          ))}
        </nav>
      </section>

      {/* AI-Generated Practice Quizzes */}
      {autoQuizzesError && (
        <p role="status" className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-sm text-amber-800 dark:border-amber-900 dark:bg-amber-950/30 dark:text-amber-200">
          Personalized practice quizzes are temporarily unavailable. Your study progress is still up to date.
        </p>
      )}
      {autoQuizzes.length > 0 && (
        <div>
          <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
            <h2 className="flex items-center gap-2 text-lg font-semibold text-foreground">
              <span aria-hidden="true">✨</span>
              Practice your focus areas
            </h2>
            <Link
              href="/assessment"
              className="inline-flex items-center gap-1 text-sm font-medium text-blue-700 hover:underline dark:text-blue-300"
            >
              All quizzes <ChevronRight aria-hidden="true" className="h-4 w-4" />
            </Link>
          </div>
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3">
            {autoQuizzes.map(quiz => (
              <AutoGeneratedQuizCard
                key={quiz.id}
                quizId={quiz.quizId}
                weaknessTopicName={quiz.weaknessTopicName}
                oldMastery={quiz.oldMastery}
                riskLevel={quiz.riskLevel}
                detectedAt={new Date(quiz.detectedAt)}
                onDismiss={() => {
                  queryClient.setQueryData<AutoGeneratedQuiz[]>(
                    ['autoGeneratedQuizzes', userId],
                    current => current?.filter(item => item.id !== quiz.id),
                  );
                }}
              />
            ))}
          </div>
        </div>
      )}

      {/* Stats Overview */}
      <section aria-labelledby="weekly-study-summary" className="space-y-3">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div>
            <h2 id="weekly-study-summary" className="text-lg font-semibold text-foreground">
              This week
            </h2>
            <p className="text-sm text-muted-foreground">A quick look at your study momentum.</p>
          </div>
          <div className="flex gap-4 text-sm">
            <Link href="/progress" className="font-medium text-blue-700 hover:underline dark:text-blue-300">
              Progress
            </Link>
            <Link href="/analytics" className="font-medium text-blue-700 hover:underline dark:text-blue-300">
              Analytics
            </Link>
          </div>
        </div>
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
          <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
            <h6 className="text-sm font-semibold text-foreground dark:text-foreground">Study time</h6>
            <p className="mt-1 text-3xl font-bold text-blue-600 dark:text-blue-400">
              {formatStudyTime(stats?.totalTime || 0)}
            </p>
            <p className="text-xs text-muted-foreground dark:text-muted-foreground">This week</p>
          </div>
          <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
            <h6 className="text-sm font-semibold text-foreground dark:text-foreground">Sessions</h6>
            <p className="mt-1 text-3xl font-bold text-blue-600 dark:text-blue-400">{stats?.totalSessions || 0}</p>
            <p className="text-xs text-muted-foreground dark:text-muted-foreground">Completed</p>
          </div>
          <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
            <h6 className="flex items-center gap-2 text-sm font-semibold text-foreground dark:text-foreground">
              <Flame aria-hidden="true" className="h-4 w-4 text-orange-500" />
              Current streak
            </h6>
            <p className="mt-1 text-3xl font-bold text-blue-600 dark:text-blue-400">
              {stats?.currentStreak || 0}
            </p>
            <p className="text-xs text-muted-foreground">
              {stats?.currentStreak === 1 ? 'day in a row' : 'days in a row'}
            </p>
          </div>
        </div>
      </section>

      <div>
        <ReviewQueue />
      </div>

      {courseProgress.length > 0 && (
      <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
        <h6 className="text-lg font-semibold mb-2 text-foreground dark:text-foreground">Course Progress</h6>
        {courseProgress.map(course => (
          <button
            key={course.id}
            type="button"
            onClick={() => router.push(`/courses/${course.id}`)}
            className="mb-3 block w-full rounded-lg p-2 text-left transition-colors hover:bg-background dark:hover:bg-card/70"
          >
            <div className="flex justify-between mb-1">
              <p className="text-base text-foreground dark:text-muted-foreground">{course.name}</p>
              <p className="text-sm text-muted-foreground dark:text-muted-foreground">{course.progressPercentage}%</p>
            </div>
            <div className="w-full h-2">
              <ProgressBar value={course.progressPercentage} className="h-2 rounded-full" />
            </div>
            <p className="text-xs text-muted-foreground dark:text-muted-foreground mt-1">
              Last synced: {formatLastUpdated(course.lastUpdated)}
            </p>
          </button>
        ))}
      </div>
      )}

      {unitProgress.length > 0 && (
      <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
        <h6 className="text-lg font-semibold mb-2 text-foreground dark:text-foreground">Unit Progress</h6>
        {unitProgress.map(unit => {
          const courseName = courseProgress.find(course => course.id === unit.courseId)?.name;

          return (
            <button
              key={unit.id}
              type="button"
              disabled={!unit.id}
              onClick={() => {
                if (unit.courseId) {
                  router.push(`/courses/${unit.courseId}/units/${unit.id}`);
                } else if (unit.id) {
                  router.push(`/unit/${unit.id}`);
                }
              }}
              className="mb-3 block w-full rounded-lg p-2 text-left transition-colors hover:bg-background disabled:cursor-default disabled:hover:bg-transparent dark:hover:bg-card/70"
            >
              <div className="flex justify-between mb-1">
                <p className="text-base text-foreground dark:text-muted-foreground">
                  {unit.name}
                  {courseName ? ` (${courseName})` : ''}
                </p>
                <p className="text-sm text-muted-foreground dark:text-muted-foreground">{unit.progressPercentage}%</p>
              </div>
              <div className="w-full h-2">
                <ProgressBar value={unit.progressPercentage} className="h-2 rounded-full" />
              </div>
              <p className="text-xs text-muted-foreground dark:text-muted-foreground mt-1">
                Last synced: {formatLastUpdated(unit.lastUpdated)}
              </p>
            </button>
          );
        })}
      </div>
      )}

      {/* Peer Comparison */}
      {peerStats && (
      <div className="bg-card/80 dark:bg-card/50 backdrop-blur-sm rounded-lg shadow-sm border border-border dark:border-border/50 p-4">
        <div className="flex items-center justify-between mb-2">
          <h6 className="text-lg font-semibold text-foreground dark:text-foreground">
            Peer Comparison
          </h6>
          {peerStats?.cohortLabel && (
            <span className="text-xs px-2 py-0.5 rounded-full bg-primary/10 text-primary font-medium">
              {peerStats.cohortLabel}
            </span>
          )}
        </div>
        {peerStats && (
          <div>
            <p className="text-sm text-muted-foreground dark:text-muted-foreground mb-2">
              You're in the top {Math.round(peerStats.userPercentile)}% of your cohort
            </p>
            <div className="mt-2 space-y-1">
              <p className="text-sm text-muted-foreground dark:text-muted-foreground">
                Cohort Average: {Math.round(peerStats.averageScore)}%
              </p>
              <p className="text-sm text-muted-foreground dark:text-muted-foreground">
                Your Completion: {Math.round(peerStats.userScore)}%
              </p>
            </div>
          </div>
        )}
      </div>
      )}

      {/* Goals Integration */}
      <div>
        <GoalsProgressWidget />
      </div>
    </div>
  );
};

function formatStudyTime(totalMinutes: number): string {
  const minutes = Math.max(0, Math.round(totalMinutes));
  if (minutes < 60) return `${minutes}m`;
  const hours = Math.floor(minutes / 60);
  const remainingMinutes = minutes % 60;
  return remainingMinutes === 0 ? `${hours}h` : `${hours}h ${remainingMinutes}m`;
}
